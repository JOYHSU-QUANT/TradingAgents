#!/bin/sh
# The carry coordinator's daily run, for a systemd timer (carry-signal.timer
# runs it at 23:50 UTC, and carry-signal.service retries it once five
# minutes later when it failed) or any other scheduler. It appends the
# command's output to a log file and exits as the command did: 0 the handoff
# is written, 1 refused (the log says why), 2 usage. It exits 4 itself when
# it cannot get to the repository or write the log, or PYTHON names a path
# that is not there: the command is not run then. See contrib/carry/RUNBOOK.md.
#
# One run is one command, python -m contrib.carry signal (contrib/carry/README.md),
# with each leg's store for the sizing once that leg's run id is set. Leave
# PERP_RUN_ID / SPOT_RUN_ID empty until the run has written its first row:
# the command refuses a run id it cannot find (a typo reads the same as a
# new run), and with the flags left out it sizes the two legs as equal
# capital, which is what two runs opened with the same balance are.
set -u

# The settings. To change one, do not edit this file: put its line in
# carry-signal.local.sh beside it (gitignored), which is read next, as
# NAME="value", one per line, nothing else (the file is sourced). A relative
# path is taken from the repository root, where the run happens.
COIN=ETH
HANDOFF=contrib/carry/data/handoff-ETH.json
RESEARCH_DB=contrib/carry/data/autoresearch.sqlite
LOG=contrib/carry/data/carry-signal.log
PERP_DB=
PERP_RUN_ID=
SPOT_DB=
SPOT_RUN_ID=
# The rule's flags (carry plan section 2 D6), split on whitespace: for example
# "--margin-pct 30 --z-in 1.5". The margin must sit on the perp run's grid
# (RUNBOOK.md), or every perp cycle fails closed off-grid.
SIGNAL_ARGS=""
# The python that has the perp and research packages' requirements
# installed: the Hyperliquid checkout's venv, as a rule.
PYTHON=python3
here=$(cd "$(dirname "$0")" && pwd) || exit 4
if [ -f "$here/carry-signal.local.sh" ]; then . "$here/carry-signal.local.sh"; fi

# What the command prints reaches the log as it is printed, so a run the
# scheduler stops still leaves its lines behind.
export PYTHONUNBUFFERED=1
# The repository root: the packages are imported from here.
cd "$here/../../.." || exit 4
mkdir -p "$(dirname "$LOG")" 2>/dev/null
# A log that cannot be written would hide what the run did: stop.
echo "==== $(date -u +%Y-%m-%dT%H:%M:%SZ) carry signal $COIN (handoff \"$HANDOFF\", research db \"$RESEARCH_DB\", python \"$PYTHON\")" >>"$LOG" 2>/dev/null || exit 4
say() {
    echo "==== $*" >>"$LOG"
}
finish() {
    say "exit $1"
    exit "$1"
}
# A PYTHON given as a path that is not there is a setting to fix, not a
# "try again later".
case "$PYTHON" in
*/*)
    if [ ! -x "$PYTHON" ]; then
        say "there is no \"$PYTHON\": fix PYTHON in carry-signal.local.sh"
        finish 4
    fi
    ;;
esac

# A run id and its store go together: one without the other is a settings
# error, said here, not a store the command cannot find at 23:50.
# pair LEG RUN_ID DB: x = the run id alone is set, y = the store alone.
pair() {
    case "${2:+x}${3:+y}" in
    x | y)
        say "${1}_DB and ${1}_RUN_ID go together, one is empty: fix carry-signal.local.sh"
        finish 1
        ;;
    esac
}
pair PERP "$PERP_RUN_ID" "$PERP_DB"
pair SPOT "$SPOT_RUN_ID" "$SPOT_DB"
set -- signal --coin "$COIN" --out "$HANDOFF" --research-db "$RESEARCH_DB"
if [ -n "$PERP_RUN_ID" ]; then
    set -- "$@" --perp-db "$PERP_DB" --perp-run-id "$PERP_RUN_ID"
else
    say "PERP_RUN_ID is empty: the perp equity is not read; the legs are sized as equal capital"
fi
if [ -n "$SPOT_RUN_ID" ]; then
    set -- "$@" --spot-db "$SPOT_DB" --spot-run-id "$SPOT_RUN_ID"
else
    say "SPOT_RUN_ID is empty: the spot equity is not read; the legs are sized as equal capital"
fi
# A log that stopped taking writes would turn into a redirect failure, exit 2
# under dash, which reads as a usage error: it is 4.
[ -w "$LOG" ] || exit 4
# SIGNAL_ARGS is unquoted on purpose: it holds flags, not a path.
"$PYTHON" -m contrib.carry "$@" $SIGNAL_ARGS >>"$LOG" 2>&1
finish $?
